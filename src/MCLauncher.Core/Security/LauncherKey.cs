namespace MCLauncher.Core.Security;

/// <summary>
/// 启动器固定密钥：账号数据必须先过这一层，再交给本机密钥包装。
/// 密钥不直接以明文常量出现——拆成三段混淆份额，运行时按位异或还原，
/// 提高逆向时直接从字符串/常量表拿到完整密钥的门槛（属于防呆，不是强安全边界）。
/// </summary>
internal static class LauncherKey
{
    private static readonly byte[] ShareA =
    {
        0x9E, 0x2C, 0x5A, 0x11, 0x73, 0xC4, 0x08, 0xF6,
        0x3D, 0x81, 0xBE, 0x27, 0x54, 0x9A, 0x6F, 0xE0,
        0x1B, 0x47, 0xAD, 0x32, 0x88, 0x0C, 0x5E, 0xD1,
        0x29, 0x76, 0xEB, 0x40, 0x93, 0x17, 0xCC, 0x65,
    };

    private static readonly byte[] ShareB =
    {
        0x3F, 0xD8, 0xA6, 0x7B, 0x0E, 0x52, 0xC9, 0x14,
        0xE5, 0x2A, 0x6D, 0x98, 0xF1, 0x03, 0x47, 0xBC,
        0x80, 0x5F, 0x22, 0x9D, 0x64, 0xB7, 0x0A, 0x3E,
        0x71, 0xC8, 0x05, 0x9B, 0x26, 0x84, 0xD5, 0x19,
    };

    private static readonly byte[] ShareC =
    {
        0x74, 0x5B, 0xE2, 0x08, 0x3C, 0x91, 0xA7, 0x6E,
        0xD4, 0x0F, 0x58, 0xB3, 0x20, 0xC6, 0x8D, 0x51,
        0xE9, 0x7A, 0x34, 0x0C, 0xB5, 0x62, 0xF7, 0x2D,
        0x9E, 0x40, 0x88, 0x13, 0x6B, 0xA1, 0xC4, 0x37,
    };

    private static byte[] Materialize()
    {
        var key = new byte[ShareA.Length];
        for (var i = 0; i < key.Length; i++)
        {
            key[i] = (byte)(ShareA[i] ^ ShareB[i] ^ ShareC[i]);
        }

        return key;
    }

    public static byte[] Wrap(byte[] data) => AesGcmBox.Wrap(Materialize(), data);

    public static byte[] Unwrap(byte[] data) => AesGcmBox.Unwrap(Materialize(), data);
}
